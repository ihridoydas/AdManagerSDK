package com.hridoy.ads

object AdFrequency {
    private const val DEFAULT_SHOW_EVERY = 3

    private var clickCount = 0
    var showEvery = DEFAULT_SHOW_EVERY

    fun canShow(): Boolean {
        clickCount++

        if (clickCount >= showEvery) {
            clickCount = 0
            return true
        }

        return false
    }
}
